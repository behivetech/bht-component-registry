import * as React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { runProgram } from "../../src/components/docs/sandbox-run";
import { BASE_SCOPE } from "../../src/components/docs/sandbox-base-scope";
import {
  resolvePackages,
  stylePackages,
} from "../../src/components/docs/sandbox-resolve";

/** What the build needs to render one catalog tile's thumbnail. */
export interface ThumbnailInput {
  packageName: string;
  /** The tile's program, or null when the component has no thumbnail. */
  code: string | null;
}

/**
 * Renders each tile's thumbnail program to static markup, once, at build time.
 *
 * A tile is inert (no frame, no interaction), so the browser never needs the
 * component behind it: the markup goes into the page, and the tile's styles
 * come from the page's own stylesheet. The whole registry is in scope here
 * because this runs in Node, where loading it costs the visitor nothing.
 *
 * A program that throws while rendering gets no thumbnail and a warning; its
 * tile shows the placeholder rather than failing the build.
 *
 * @param inputs the tiles to render
 * @param modules every package's exports, by package name
 * @param warnings collects a message per thumbnail that could not render
 * @returns package name → markup, for the tiles that rendered
 */
export const renderThumbnails = async (
  inputs: ThumbnailInput[],
  modules: Map<string, Record<string, unknown>>,
  warnings: string[],
): Promise<Record<string, string>> => {
  const scope: Record<string, unknown> = { ...BASE_SCOPE };
  for (const mod of modules.values()) {
    Object.assign(scope, mod);
  }
  delete scope.default;

  const html: Record<string, string> = {};
  for (const { packageName, code } of inputs) {
    if (code === null) continue;
    try {
      // A tile's program is an example, which ends in `render(...)`.
      const element = await new Promise<React.ReactElement | null>(
        (resolve, reject) => {
          runProgram({ code, noInline: true }, scope, {
            onElement: resolve,
            onError: reject,
          });
        },
      );
      // Each tile is its own React root: without a prefix of its own, every
      // tile's `useId` counter starts at the same value and the page repeats ids.
      html[packageName] = renderToStaticMarkup(element, {
        identifierPrefix: `${packageName.replace(/^@[^/]+\//, "").replace(/[^\w-]/g, "-")}-`,
      });
    } catch (error) {
      warnings.push(
        `${packageName}: thumbnail not rendered — ${(error as Error).message.split("\n")[0]}`,
      );
    }
  }
  return html;
};

/**
 * The generated `thumbnail-styles.ts`: a static import of the stylesheet of
 * every package a thumbnail paints with, itself and what it uses.
 *
 * Only the scope page imports it, so Next puts these sheets in that route's CSS
 * and no other page carries them. Sorted, the order every package's styles
 * have always loaded in, so a package that restyles one it uses still wins.
 *
 * @param codes the thumbnail programs that rendered
 * @param exportIndex export name → package
 * @param dependencies package → the registry packages it uses
 * @param styled the packages that publish a stylesheet
 * @returns the module's source
 */
export const thumbnailStylesModule = (
  codes: string[],
  exportIndex: Record<string, string>,
  dependencies: Record<string, string[]>,
  styled: Set<string>,
): string => {
  const used = codes.flatMap((code) => resolvePackages(code, exportIndex));
  const packages = stylePackages(used, dependencies).filter((name) =>
    styled.has(name),
  );
  return [
    "// GENERATED by scripts/generate-catalog.ts — do not edit.",
    "// The styles of every package a catalog tile's thumbnail renders.",
    "",
    ...packages.map((name) => `import "${name}/styles.css";`),
    "",
  ].join("\n");
};
